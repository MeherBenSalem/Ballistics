def _r(v):
    return [round(float(x), 3) for x in v]


def gun_display(g):
    lo, hi = g.model.bounds()
    center = [(lo[i] + hi[i]) / 2 for i in range(3)]
    length = hi[2] - lo[2]
    pivot = g.visuals["pivot"]
    pistol = g.visuals["animations"].split(":")[1] in ("pistol", "revolver")
    s_hand = 0.42 if pistol else 0.4

    def centred(point, s, rot=(0, 0, 0)):
        rel = np.array(point) - 8.0
        m = rotation_matrix("x", rot[0]) @ rotation_matrix("y", rot[1]) @ rotation_matrix("z", rot[2])
        return _r(-(m @ rel) * s)

    s_fixed = min(0.9, 15.0 / length)
    s_ground = min(0.5, 9.0 / length)
    return {
        "thirdperson_righthand": {"rotation": [0, 0, 0], "translation": centred(pivot, s_hand), "scale": [s_hand] * 3},
        "thirdperson_lefthand": {"rotation": [0, 0, 0], "translation": centred(pivot, s_hand), "scale": [s_hand] * 3},
        "firstperson_righthand": {"rotation": [0, 0, 0], "translation": _r(np.array(centred(pivot, 0.5)) + np.array([2.0, 1.0, -3.0])), "scale": [0.5] * 3},
        "firstperson_lefthand": {"rotation": [0, 0, 0], "translation": _r(np.array(centred(pivot, 0.5)) + np.array([2.0, 1.0, -3.0])), "scale": [0.5] * 3},
        "ground": {"rotation": [0, 0, 0], "translation": centred(center, s_ground), "scale": [s_ground] * 3},
        "fixed": {"rotation": [0, -90, 0], "translation": centred(center, s_fixed, (0, -90, 0)), "scale": [s_fixed] * 3},
        "head": {"rotation": [0, 0, 0], "translation": _r(np.array(centred(center, 0.6)) + np.array([0, 6, 0])), "scale": [0.6] * 3},
        "gui": {"rotation": [0, 0, 0], "translation": [0, 0, 0], "scale": [1, 1, 1]},
    }


