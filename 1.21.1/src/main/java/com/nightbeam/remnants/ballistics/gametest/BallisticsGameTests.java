/**
 * Server-side integration tests. Weapons are fired through the same entry point as network packets
 * ({@link ServerWeaponHandler#fire}), by a {@link FakePlayer} that the test ticks itself.
 * <p>
 * Template {@code remnants_ballistics:range}: a 5 x 5 x 13 corridor with a stone floor (generated by tools/assets).
 * Run with {@code ./gradlew runGameTestServer}.
 */
@GameTestHolder(RemnantsBallistics.MODID)
@PrefixGameTestTemplate(false)
public final class BallisticsGameTests {
    private static final String RANGE = "range";
    private static final BlockPos SHOOTER = new BlockPos(2, 1, 1);

    private BallisticsGameTests() {}

    // ------------------------------------------------------------------------------------------------------------
    // Helpers
    // ------------------------------------------------------------------------------------------------------------

    /** A fake player at the shooting position holding a fully loaded weapon, looking at {@code target} (relative). */
    private static FakePlayer shooter(GameTestHelper helper, String weapon, Vec3 target) {
        ServerLevel level = helper.getLevel();
        FakePlayer player = FakePlayerFactory.get(level, new GameProfile(UUID.randomUUID(), "rb_test"));
        Vec3 feet = helper.absoluteVec(Vec3.atBottomCenterOf(SHOOTER));
        Vec3 aim = helper.absoluteVec(target);
        Vec3 eye = feet.add(0, player.getEyeHeight(), 0);
        Vec3 d = aim.subtract(eye);
        float yaw = (float) (Mth.atan2(d.z, d.x) * Mth.RAD_TO_DEG) - 90f;
        float pitch = (float) -(Mth.atan2(d.y, Math.sqrt(d.x * d.x + d.z * d.z)) * Mth.RAD_TO_DEG);
        player.moveTo(feet.x, feet.y, feet.z, yaw, pitch);
        player.setYHeadRot(yaw);
        player.getInventory().clearContent();
        player.getInventory().selected = 0;
        player.getInventory().setItem(0, GunData.loaded(ModItems.gun(weapon)));
        ServerWeaponHandler.tick(player); // registers the equip and starts the draw delay
        return player;
    }

    private static void fire(FakePlayer player, int sequence) {
        ServerWeaponHandler.fire(player, new FireWeaponPayload(player.getInventory().selected, sequence, player.getYRot(), player.getXRot(), 0f));
    }

    private static int ammo(FakePlayer player) {
        return GunData.ammo(player.getInventory().getSelected());
    }

    /** Ticks the shooter until its weapon is drawn and fully aimed. */
    private static void readyAndAimed(GameTestHelper helper, FakePlayer player, long startTick) {
        ServerWeaponHandler.tick(player);
        helper.assertTrue(helper.getLevel().getGameTime() >= startTick + ShooterState.EQUIP_TICKS + 24, "weapon still being drawn and aimed");
    }

    // ------------------------------------------------------------------------------------------------------------
    // Firing
    // ------------------------------------------------------------------------------------------------------------

    @GameTest(template = RANGE, timeoutTicks = 200)
    public static void hitscanDamagesTarget(GameTestHelper helper) {
        Pig pig = helper.spawnWithNoFreeWill(EntityType.PIG, new BlockPos(2, 1, 9));
        float before = pig.getHealth();
        FakePlayer player = shooter(helper, "arx_16", new Vec3(2.5, 1.5, 9.5));
        long start = helper.getLevel().getGameTime();
        ServerWeaponHandler.setAiming(player, true);
        helper.startSequence()
                .thenWaitUntil(() -> readyAndAimed(helper, player, start))
                .thenExecute(() -> fire(player, 1))
                .thenExecute(() -> helper.assertTrue(!pig.isAlive() || pig.getHealth() < before, "aimed rifle shot did not damage the target"))
                .thenExecute(() -> helper.assertValueEqual(ammo(player), GunData.maxCapacity(Weapons.ARX_16,
                        GunData.stats(player.getInventory().getSelected(), Weapons.ARX_16)) - 1, "rounds left after one shot"))
                .thenSucceed();
    }

    @GameTest(template = RANGE, timeoutTicks = 200)
    public static void bulletsBreakGlass(GameTestHelper helper) {
        BlockPos glass = new BlockPos(2, 2, 7);
        helper.setBlock(glass, Blocks.GLASS);
        FakePlayer player = shooter(helper, "r9_sidearm", Vec3.atCenterOf(glass));
        long start = helper.getLevel().getGameTime();
        ServerWeaponHandler.setAiming(player, true);
        helper.startSequence()
                .thenWaitUntil(() -> readyAndAimed(helper, player, start))
                .thenExecute(() -> fire(player, 1))
                .thenExecute(() -> helper.assertBlockPresent(Blocks.AIR, glass))
                .thenSucceed();
    }

    @GameTest(template = RANGE, timeoutTicks = 200)
    public static void fireRateIsEnforced(GameTestHelper helper) {
        FakePlayer player = shooter(helper, "ghostline_m24", new Vec3(2.5, 2.5, 12.0));
        long start = helper.getLevel().getGameTime();
        helper.startSequence()
                .thenWaitUntil(() -> readyAndAimed(helper, player, start))
                .thenExecute(() -> {
                    int before = ammo(player);
                    fire(player, 1);
                    fire(player, 2); // same tick: must be rejected by the rate limiter (48 RPM)
                    fire(player, 2); // replayed sequence number: must be ignored
                    helper.assertValueEqual(ammo(player), before - 1, "rounds fired in one tick");
                })
                .thenSucceed();
    }

    @GameTest(template = RANGE, timeoutTicks = 100)
    public static void drawDelayBlocksFiring(GameTestHelper helper) {
        FakePlayer player = shooter(helper, "viper_9", new Vec3(2.5, 2.5, 12.0));
        int before = ammo(player);
        fire(player, 1); // weapon was equipped this tick
        helper.assertValueEqual(ammo(player), before, "rounds fired while drawing");
        helper.succeed();
    }

    @GameTest(template = RANGE, timeoutTicks = 200)
    public static void emptyWeaponDoesNotFire(GameTestHelper helper) {
        FakePlayer player = shooter(helper, "raven_ak", new Vec3(2.5, 2.5, 12.0));
        GunData.setAmmo(player.getInventory().getSelected(), 0);
        long start = helper.getLevel().getGameTime();
        helper.startSequence()
                .thenWaitUntil(() -> readyAndAimed(helper, player, start))
                .thenExecute(() -> {
                    fire(player, 1);
                    helper.assertValueEqual(ammo(player), 0, "rounds after dry fire");
                })
                .thenSucceed();
    }

    @GameTest(template = RANGE, timeoutTicks = 200)
    public static void voidcasterLaunchesOrb(GameTestHelper helper) {
        FakePlayer player = shooter(helper, "voidcaster", new Vec3(2.5, 2.0, 12.0));
        long start = helper.getLevel().getGameTime();
        helper.startSequence()
                .thenWaitUntil(() -> readyAndAimed(helper, player, start))
                .thenExecute(() -> {
                    fire(player, 1);
                    helper.assertEntityPresent(ModEntities.VOID_ORB.get());
                })
                .thenSucceed();
    }

    // ------------------------------------------------------------------------------------------------------------
    // Reloading
    // ------------------------------------------------------------------------------------------------------------

    @GameTest(template = RANGE, timeoutTicks = 400)
    public static void magazineReloadUsesReserve(GameTestHelper helper) {
        FakePlayer player = shooter(helper, "arx_16", new Vec3(2.5, 2.5, 12.0));
        ItemStack gun = player.getInventory().getSelected();
        WeaponDefinition def = Weapons.ARX_16;
        int magazine = GunData.stats(gun, def).getInt(Stat.MAGAZINE);
        GunData.setAmmo(gun, 0);
        player.getInventory().setItem(5, new ItemStack(ModItems.ammo(AmmoType.RIFLE_556), 64));
        long start = helper.getLevel().getGameTime();
        helper.startSequence()
                .thenWaitUntil(() -> readyAndAimed(helper, player, start))
                .thenExecute(() -> ServerWeaponHandler.startReload(player, 0))
                .thenWaitUntil(() -> {
                    ServerWeaponHandler.tick(player);
                    helper.assertTrue(GunData.ammo(player.getInventory().getSelected()) > 0, "magazine not loaded yet");
                })
                .thenExecute(() -> {
                    helper.assertValueEqual(GunData.ammo(player.getInventory().getSelected()), magazine, "rounds after an empty reload");
                    helper.assertValueEqual(AmmoInventory.count(player, AmmoType.RIFLE_556), 64 - magazine, "reserve after reload");
                })
                .thenSucceed();
    }

    @GameTest(template = RANGE, timeoutTicks = 600)
    public static void singleLoadReloadInsertsRounds(GameTestHelper helper) {
        FakePlayer player = shooter(helper, "thunderpump", new Vec3(2.5, 2.5, 12.0));
        GunData.setAmmo(player.getInventory().getSelected(), 0);
        player.getInventory().setItem(5, new ItemStack(ModItems.ammo(AmmoType.SHOTGUN_12G), 3));
        long start = helper.getLevel().getGameTime();
        helper.startSequence()
                .thenWaitUntil(() -> readyAndAimed(helper, player, start))
                .thenExecute(() -> ServerWeaponHandler.startReload(player, 0))
                .thenWaitUntil(() -> {
                    ServerWeaponHandler.tick(player);
                    helper.assertValueEqual(GunData.ammo(player.getInventory().getSelected()), 3, "shells loaded");
                })
                .thenExecute(() -> helper.assertValueEqual(AmmoInventory.count(player, AmmoType.SHOTGUN_12G), 0, "shells left in reserve"))
                .thenSucceed();
    }

    // ------------------------------------------------------------------------------------------------------------
    // Data
    // ------------------------------------------------------------------------------------------------------------

    @GameTest(template = RANGE)
    public static void ammoPressRecipeMatches(GameTestHelper helper) {
        AmmoPressInput input = new AmmoPressInput(List.of(new ItemStack(Items.GUNPOWDER, 2), new ItemStack(ModItems.CASING.get(), 8),
                new ItemStack(Items.COPPER_INGOT)));
        var match = helper.getLevel().getRecipeManager().getRecipeFor(ModRecipes.AMMO_PRESS_TYPE.get(), input, helper.getLevel());
        helper.assertTrue(match.isPresent(), "no ammo press recipe for casings + gunpowder + copper");
        ItemStack result = match.get().value().getResultItem(helper.getLevel().registryAccess());
        helper.assertTrue(result.is(ModItems.ammo(AmmoType.PISTOL_9MM)), "expected 9mm rounds, got " + result);
        helper.succeed();
    }

    @GameTest(template = RANGE)
    public static void everyWeaponIsCraftable(GameTestHelper helper) {
        var recipes = helper.getLevel().getRecipeManager();
        for (WeaponDefinition def : Weapons.all()) {
            helper.assertTrue(recipes.byKey(RemnantsBallistics.id(def.name())).isPresent(), "missing crafting recipe for " + def.name());
            GunItem item = ModItems.gun(def);
            helper.assertTrue(item.definition() == def, "item/definition mismatch for " + def.name());
        }
        helper.succeed();
    }

    @GameTest(template = RANGE)
    public static void lootAndDamageDataLoaded(GameTestHelper helper) {
        var server = helper.getLevel().getServer();
        for (String table : List.of("inject/outpost", "inject/stronghold", "inject/end_city", "inject/armed_mob")) {
            LootTable loaded = server.reloadableRegistries().getLootTable(ResourceKey.create(Registries.LOOT_TABLE, RemnantsBallistics.id(table)));
            helper.assertTrue(loaded != LootTable.EMPTY, "loot table " + table + " missing");
        }
        var damageTypes = helper.getLevel().registryAccess().registryOrThrow(Registries.DAMAGE_TYPE);
        for (var key : List.of(ModDamageTypes.BULLET, ModDamageTypes.BULLET_HEADSHOT, ModDamageTypes.ENERGY)) {
            helper.assertTrue(damageTypes.getHolder(key).isPresent(), "damage type " + key.location() + " missing");
        }
        helper.succeed();
    }
}
