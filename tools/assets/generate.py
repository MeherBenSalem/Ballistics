def _nbt(tag, value):
    """Minimal big-endian NBT payload encoder (compound, list, int, string)."""
    import struct
    if tag == "int":
        return struct.pack(">i", value)
    if tag == "string":
        b = value.encode("utf-8")
        return struct.pack(">H", len(b)) + b
    if tag == "list":
        elem_tag, items = value
        ids = {"int": 3, "compound": 10, "end": 0}
        return struct.pack(">bi", ids[elem_tag], len(items)) + b"".join(_nbt(elem_tag, v) for v in items)
    if tag == "compound":
        ids = {"int": 3, "string": 8, "list": 9, "compound": 10}
        out = b""
        for name, (t, v) in value.items():
            out += struct.pack(">b", ids[t]) + _nbt("string", name) + _nbt(t, v)
        return out + b"\x00"
    raise ValueError(tag)


def gen_structures(report):
    """GameTest template remnants_ballistics:range - a 5 x 5 x 13 corridor with a smooth stone floor."""
    import gzip
    sx, sy, sz = 5, 5, 13
    blocks = []
    for x in range(sx):
        for y in range(sy):
            for z in range(sz):
                blocks.append(("compound", {"pos": ("list", ("int", [x, y, z])), "state": ("int", 0 if y == 0 else 1)}))
    root = {
        "DataVersion": ("int", 3955),
        "size": ("list", ("int", [sx, sy, sz])),
        "palette": ("list", ("compound", [{"Name": ("string", "minecraft:smooth_stone")}, {"Name": ("string", "minecraft:air")}])),
        "blocks": ("list", ("compound", [b[1] for b in blocks])),
        "entities": ("list", ("end", [])),
    }
    data = b"\x0a" + _nbt("string", "") + _nbt("compound", root)
    path = os.path.join(DATA, "structure", "range.nbt")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with gzip.GzipFile(path, "wb", mtime=0) as f:
        f.write(data)
    report.append("structure: GameTest template range (5x5x13)")


def gen_data(report, weapons, attachments, ammo):
    for name, r in data_gen.recipes(weapons, attachments).items():
        write_json(os.path.join(DATA, "recipe", name + ".json"), r)
    for name, t in data_gen.loot_tables().items():
        write_json(os.path.join(DATA, "loot_table", name + ".json"), t)
    # Read from the mod jar by LootInjections (not a datapack folder: it must be known before loot tables load).
    write_json(os.path.join(DATA, "loot_injections.json"), {"injections": data_gen.loot_injections()})
    legendary = ["longshot_50", "eclipse_railgun"]
    own, vanilla = data_gen.tags(weapons, attachments, ammo, legendary)
    for path, values in own.items():
        write_json(os.path.join(DATA, "tags", path + ".json"), {"replace": False, "values": values})
    for path, values in vanilla.items():
        ns, rest = path.split("/", 1)
        write_json(os.path.join(RES, "data", ns, rest + ".json"), {"replace": False, "values": values})
    for name, d in data_gen.damage_types().items():
        write_json(os.path.join(DATA, "damage_type", name + ".json"), d)
    for name, a in data_gen.advancements().items():
        write_json(os.path.join(DATA, "advancement", name + ".json"), a)
    report.append(f"data: recipes, {len(data_gen.loot_injections())} loot injections, tags, damage types, advancements")


def main():
    no_sound = "--no-sound" in sys.argv
    # Clean generated trees (sounds are kept when skipping synthesis).
    for path in (os.path.join(ASSETS, "models"), os.path.join(ASSETS, "textures"), os.path.join(ASSETS, "animations"),
                 os.path.join(ASSETS, "gun_visuals"), os.path.join(ASSETS, "blockstates"), os.path.join(ASSETS, "particles"),
                 os.path.join(RES, "data"), BLOCKBENCH):
        shutil.rmtree(path, ignore_errors=True)
    report = []
    weapons = gen_weapons(report)
    attachments = gen_attachments(report)
    item_names = gen_items(report)
    gen_blocks(report)
    gen_art(report, gun_defs.arx_16)
    ammo = [n for n in item_names if n.startswith("ammo_") or n == "energy_cell"]
    gen_data(report, weapons, attachments, ammo)
    gen_structures(report)
    import sfx
    if no_sound:
        subtitles = {f"subtitles.{NS}.{event}": sub for event, _, _, _, sub in sfx.catalogue()}
    else:
        shutil.rmtree(os.path.join(ASSETS, "sounds"), ignore_errors=True)
        sounds_json, subtitles = sfx.generate(ASSETS, NS)
        write_json(os.path.join(ASSETS, "sounds.json"), sounds_json)
        report.append(f"audio: {len(sounds_json)} sound events")
    write_json(os.path.join(ASSETS, "lang", "en_us.json"), lang.build(JAVA_CONFIG, subtitles))
    for game in port_resources.TARGETS:
        port_resources.port(game)
    for line in report:
        print(line)


if __name__ == "__main__":
    main()
