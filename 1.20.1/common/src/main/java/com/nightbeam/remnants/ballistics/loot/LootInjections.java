package com.nightbeam.remnants.ballistics.loot;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.nightbeam.remnants.ballistics.RemnantsBallistics;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.storage.loot.LootPool;
import net.minecraft.world.level.storage.loot.entries.LootTableReference;
import net.minecraft.world.level.storage.loot.predicates.LootItemKilledByPlayerCondition;
import net.minecraft.world.level.storage.loot.providers.number.ConstantValue;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Extra loot rolled into vanilla tables: structure chests and armed mobs. The list is generated by
 * {@code tools/assets/data_gen.py} into {@code data/remnants_ballistics/loot_injections.json} and read straight from the
 * mod jar, because loader hooks add the pools while the target tables load, before any datapack listener could run.
 * <p>
 * Each injection becomes one pool: a single roll of the extra table, gated by {@link InjectionChanceCondition} (config
 * toggle, chance and {@code lootChanceMultiplier}, evaluated on every roll) and, for mobs, by a player kill.
 */
public final class LootInjections {
    private static final String RESOURCE = "/data/" + RemnantsBallistics.MODID + "/loot_injections.json";
    private static Map<ResourceLocation, List<Injection>> byTarget;

    public record Injection(String name, ResourceLocation table, String category, float chance, boolean killedByPlayer) {}

    private LootInjections() {}

    /** Injections for a loot table, in file order (empty for tables we do not touch). */
    public static List<Injection> forTable(ResourceLocation table) {
        return load().getOrDefault(table, List.of());
    }

    public static LootPool.Builder pool(Injection injection) {
        LootPool.Builder pool = LootPool.lootPool()
                .setRolls(ConstantValue.exactly(1f))
                .add(LootTableReference.lootTableReference(injection.table()))
                .when(InjectionChanceCondition.of(injection.category(), injection.chance()));
        if (injection.killedByPlayer()) pool.when(LootItemKilledByPlayerCondition.killedByPlayer());
        return pool;
    }

    private static synchronized Map<ResourceLocation, List<Injection>> load() {
        if (byTarget != null) return byTarget;
        Map<ResourceLocation, List<Injection>> map = new HashMap<>();
        try (InputStream in = LootInjections.class.getResourceAsStream(RESOURCE)) {
            if (in == null) throw new IOException(RESOURCE + " is missing from the mod jar");
            JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("injections").entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                Injection injection = new Injection(e.getKey(),
                        new ResourceLocation(o.get("table").getAsString()),
                        o.get("category").getAsString(), o.get("chance").getAsFloat(),
                        o.has("killed_by_player") && o.get("killed_by_player").getAsBoolean());
                for (JsonElement target : o.getAsJsonArray("targets")) {
                    map.computeIfAbsent(new ResourceLocation(target.getAsString()), k -> new ArrayList<>()).add(injection);
                }
            }
        } catch (IOException | RuntimeException ex) {
            RemnantsBallistics.LOGGER.error("Could not read loot injections; no loot will be added to vanilla tables", ex);
        }
        byTarget = Map.copyOf(map);
        return byTarget;
    }
}
