def gen_weapons(report):
    names = []
    for fn in gun_defs.ALL:
        g = fn()
        name = g.name
        names.append(name)
        tex, mats, uvs = build_texture(g.model, seed=seed_of(name))
        size = tex.width
        tex_id = f"{NS}:item/gun/{name}"
        save_png(tex, os.path.join(ASSETS, "textures", "item", "gun", name + ".png"))
        for skin in SKINS:
            save_png(skin_texture(tex, mats, skin, seed_of(name + skin)), os.path.join(ASSETS, "textures", "item", "gun", f"{name}_{skin}.png"))
        for part in PARTS:
            m = part_model_json(g.model, part, uvs, size, tex_id)
            m["credit"] = CREDIT
            write_json(os.path.join(ASSETS, "models", "gun", name, part + ".json"), m)
        bb = full_model_json(g.model, uvs, size, tex_id)
        bb["credit"] = CREDIT
        write_json(os.path.join(BLOCKBENCH, name + ".json"), bb)
        # Per-weapon animation set; visuals point at it.
        set_name, anim_json = anims.build(g)
        write_json(os.path.join(ASSETS, "animations", "gun", set_name + ".json"), anim_json)
        visuals = dict(g.visuals)
        visuals["animations"] = f"{NS}:{set_name}"
        write_json(os.path.join(ASSETS, "gun_visuals", name + ".json"), visuals)
        icon = render_icon(g.model, tex, uvs, yaw=90, pitch=0)
        save_png(icon, os.path.join(ASSETS, "textures", "item", "icon", name + ".png"))
        write_json(os.path.join(ASSETS, "models", "item", "icon", name + ".json"),
                   {"parent": "minecraft:item/generated", "textures": {"layer0": f"{NS}:item/icon/{name}"}})
        write_json(os.path.join(ASSETS, "models", "item", name + ".json"),
                   {"parent": "minecraft:builtin/entity", "gui_light": "front", "textures": {"particle": f"{NS}:item/icon/{name}"},
                    "display": gun_display(g)})
        report.append(f"weapon {name}: {len(g.model.boxes)} elements, texture {size}x{size}, 5 skins, animation set")
    return names


