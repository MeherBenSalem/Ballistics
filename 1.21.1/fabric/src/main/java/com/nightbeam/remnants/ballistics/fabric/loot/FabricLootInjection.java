package com.nightbeam.remnants.ballistics.fabric.loot;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.mojang.serialization.JsonOps;
import com.nightbeam.remnants.ballistics.RemnantsBallistics;
import com.nightbeam.remnants.ballistics.loot.ConfigChanceCondition;
import net.fabricmc.fabric.api.loot.v3.LootTableEvents;
import net.fabricmc.loader.api.FabricLoader;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.RegistryOps;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.storage.loot.LootPool;
import net.minecraft.world.level.storage.loot.LootTable;
import net.minecraft.world.level.storage.loot.entries.NestedLootTable;
import net.minecraft.world.level.storage.loot.predicates.LootItemCondition;
import net.minecraft.world.level.storage.loot.providers.number.ConstantValue;

import java.io.IOException;
import java.io.Reader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Loot injection on Fabric. The single source of truth is the NeoForge global loot modifier data generated by
 * {@code tools/assets} ({@code data/neoforge/loot_modifiers/global_loot_modifiers.json} and the
 * {@code remnants_ballistics:configurable_table} modifiers it lists): each one names target tables
 * ({@code neoforge:loot_table_id} conditions), extra loot conditions, the table to roll, a config category and a chance.
 * Here every target table gets one extra pool that rolls that table, gated by {@link ConfigChanceCondition} plus the extra
 * conditions, which matches the modifier's behaviour.
 */
public final class FabricLootInjection {
    private static final String LOOT_TABLE_ID = "neoforge:loot_table_id";

    private record Injection(ResourceKey<LootTable> table, String category, float chance, List<JsonElement> conditions) {}

    private FabricLootInjection() {}

    public static void register() {
        Map<ResourceLocation, List<Injection>> byTarget = load();
        RemnantsBallistics.LOGGER.debug("Loot injection into {} tables", byTarget.size());
        LootTableEvents.MODIFY.register((key, table, source, registries) -> {
            List<Injection> injections = byTarget.get(key.location());
            if (injections == null) return;
            RegistryOps<JsonElement> ops = registries.createSerializationContext(JsonOps.INSTANCE);
            for (Injection injection : injections) {
                LootPool.Builder pool = LootPool.lootPool()
                        .setRolls(ConstantValue.exactly(1))
                        .add(NestedLootTable.lootTableReference(injection.table()))
                        .when(() -> new ConfigChanceCondition(injection.category(), injection.chance()));
                for (JsonElement json : injection.conditions()) {
                    LootItemCondition condition = LootItemCondition.DIRECT_CODEC.parse(ops, json)
                            .getOrThrow(error -> new IllegalStateException("Bad loot condition " + json + ": " + error));
                    pool.when(() -> condition);
                }
                table.withPool(pool);
            }
        });
    }

    private static Map<ResourceLocation, List<Injection>> load() {
        Map<ResourceLocation, List<Injection>> byTarget = new HashMap<>();
        JsonObject global = read("data/neoforge/loot_modifiers/global_loot_modifiers.json");
        for (JsonElement entry : global.getAsJsonArray("entries")) {
            ResourceLocation id = ResourceLocation.parse(entry.getAsString());
            if (!id.getNamespace().equals(RemnantsBallistics.MODID)) continue;
            JsonObject modifier = read("data/" + id.getNamespace() + "/loot_modifiers/" + id.getPath() + ".json");
            if (!modifier.get("type").getAsString().equals(RemnantsBallistics.id("configurable_table").toString())) continue;

            List<ResourceLocation> targets = new ArrayList<>();
            List<JsonElement> conditions = new ArrayList<>();
            for (JsonElement element : modifier.getAsJsonArray("conditions")) {
                JsonObject condition = element.getAsJsonObject();
                if (!collectTargets(condition, targets)) conditions.add(condition);
            }
            ResourceKey<LootTable> table = ResourceKey.create(Registries.LOOT_TABLE, ResourceLocation.parse(modifier.get("table").getAsString()));
            float chance = modifier.has("chance") ? modifier.get("chance").getAsFloat() : 1f;
            Injection injection = new Injection(table, modifier.get("category").getAsString(), chance, conditions);
            for (ResourceLocation target : targets) byTarget.computeIfAbsent(target, k -> new ArrayList<>()).add(injection);
        }
        return byTarget;
    }

    /** Collects the table ids of a {@code loot_table_id} condition, or an {@code any_of} made only of them. */
    private static boolean collectTargets(JsonObject condition, List<ResourceLocation> targets) {
        String type = condition.get("condition").getAsString();
        if (type.equals(LOOT_TABLE_ID)) {
            targets.add(ResourceLocation.parse(condition.get("loot_table_id").getAsString()));
            return true;
        }
        if (!type.equals("minecraft:any_of")) return false;
        JsonArray terms = condition.getAsJsonArray("terms");
        for (JsonElement term : terms) {
            if (!term.getAsJsonObject().get("condition").getAsString().equals(LOOT_TABLE_ID)) return false;
        }
        for (JsonElement term : terms) targets.add(ResourceLocation.parse(term.getAsJsonObject().get("loot_table_id").getAsString()));
        return true;
    }

    private static JsonObject read(String path) {
        Path file = FabricLoader.getInstance().getModContainer(RemnantsBallistics.MODID).flatMap(mod -> mod.findPath(path))
                .orElseThrow(() -> new IllegalStateException("Missing " + path + " in the mod jar"));
        try (Reader reader = Files.newBufferedReader(file)) {
            return JsonParser.parseReader(reader).getAsJsonObject();
        } catch (IOException e) {
            throw new IllegalStateException("Cannot read " + path, e);
        }
    }
}
