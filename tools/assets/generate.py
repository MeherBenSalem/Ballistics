def render_icon(model, tex, uvs, size=32, yaw=90.0, pitch=0.0, margin=1, fill=1.0, ss=4):
    """Orthographic, game-shaded icon fitted to size x size with a 1px dark outline.

    Rendered at ss x resolution and reduced by coverage (a pixel is kept when a quarter of its samples are covered,
    taking the mean colour of the covered samples), so thin parts such as stock struts survive at 32 px.
    """
    quads = model_quads(model, tex, uvs)
    pts = np.concatenate([q.pts for q in quads])
    center = (pts.min(axis=0) + pts.max(axis=0)) / 2
    yr, pr = math.radians(yaw), math.radians(pitch)
    view = np.array([math.sin(yr) * math.cos(pr), math.sin(pr), math.cos(yr) * math.cos(pr)])
    up = np.array([0.0, 1.0, 0.0])
    cam = Camera(size, size, eye=tuple(center + view * 100), target=tuple(center), up=tuple(up), scale=1.0)
    v = cam.to_view(pts)
    span = max(v[:, 0].max() - v[:, 0].min(), v[:, 1].max() - v[:, 1].min())
    big = size * ss
    scale = (size - 2 * margin - 2) * ss / span * fill
    cx = (v[:, 0].max() + v[:, 0].min()) / 2
    cy = (v[:, 1].max() + v[:, 1].min()) / 2
    eye = center + view * 100 + cam.basis[0] * cx + cam.basis[1] * cy
    cam = Camera(big, big, eye=tuple(eye), target=tuple(eye - view), up=tuple(up), scale=scale)
    r = Renderer(big, big)
    r.draw(quads, cam, shading="mc")
    hi = np.asarray(r.image()).astype(np.float32).reshape(size, ss, size, ss, 4)
    covered = hi[..., 3] > 0
    count = covered.sum(axis=(1, 3))
    rgb_sum = (hi[..., :3] * covered[..., None]).sum(axis=(1, 3))
    out = np.zeros((size, size, 4), dtype=np.uint8)
    keep = count >= max(1, ss * ss // 4)
    out[keep, :3] = (rgb_sum[keep] / count[keep][:, None]).round().astype(np.uint8)
    out[keep, 3] = 255
    return add_outline(Image.fromarray(out, "RGBA"), darken=0.38)


